export const POSTAL_ADDRESS = '東京都千代田区神田三崎町3-2-6';
const escape = value => String(value ?? '').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
export function renderMasterEmail(locale, kind, values) {
 const row = EMAIL_MASTER[locale] || EMAIL_MASTER.en;
 const data = {postal_address: POSTAL_ADDRESS, minutes:15, ...values};
 const fill = template => template.replace(/\{\{(\w+)\}\}/g,(_,key)=>String(data[key] ?? ''));
 const subject = fill(row[kind === 'share' ? 0 : 2]).replace(/[\r\n]/g,' ');
 const text = fill(row[kind === 'share' ? 1 : 3]);
 // Escape values before linking; neither report content nor names can inject HTML.
 const html = `<html lang="${locale}"><body>${text.split('\n\n').map(p=>`<p>${escape(p).replace(/https:\/\/[^\s<]+/g,url=>`<a href="${url}">${url}</a>`).replaceAll('\n','<br>')}</p>`).join('')}</body></html>`;
 return {subject,text,html};
}
