const config = window.NUREVO_CONFIG || {};
const state = { lang: localStorage.getItem("nurevo-lang") || "en" };

document.addEventListener("DOMContentLoaded", () => {
  applyLanguage(state.lang);
  updateConfiguredLinks();
  bindTabs();
  bindCopyButtons();
  bindKeyForm();
});

function applyLanguage(lang) {
  state.lang = i18n[lang] ? lang : "en";
  document.documentElement.lang = state.lang;
  localStorage.setItem("nurevo-lang", state.lang);
  for (const element of document.querySelectorAll("[data-i18n]")) {
    const key = element.dataset.i18n;
    if (Object.hasOwn(i18n[state.lang], key)) element.textContent = i18n[state.lang][key];
  }
  for (const element of document.querySelectorAll("[data-i18n-placeholder]")) {
    const key = element.dataset.i18nPlaceholder;
    if (Object.hasOwn(i18n[state.lang], key)) element.placeholder = i18n[state.lang][key];
  }
  const toggle = document.querySelector("[data-lang-toggle]");
  if (toggle) toggle.textContent = state.lang === "ja" ? "English" : "日本語";
}

function updateConfiguredLinks() {
  const tagUrl = config.tagUrl || "https://YOUR-WORKER.example.workers.dev/tag.js";
  const snippet = `<script src="${tagUrl}" async data-webmcp-site-key="YOUR_SITE_KEY"></script>`;
  for (const snippetElement of document.querySelectorAll("#gtm-snippet, #tag-snippet")) {
    snippetElement.textContent = snippet;
  }
  document.querySelector("[data-wp-plugin-link]")?.setAttribute("href", config.wpPluginUrl || "#wordpress");
  document.querySelector("[data-docs-link]")?.setAttribute("href", config.docsUrl || "#developers");
  document.querySelector("[data-lang-toggle]")?.addEventListener("click", () => applyLanguage(state.lang === "ja" ? "en" : "ja"));
}

function bindTabs() {
  for (const tab of document.querySelectorAll("[data-tab]")) {
    tab.addEventListener("click", () => openTab(tab.dataset.tab));
  }
  for (const link of document.querySelectorAll("[data-open-tab]")) {
    link.addEventListener("click", () => openTab(link.dataset.openTab));
  }
  const initialTab = document.querySelector("[data-tab].active")?.dataset.tab || "wordpress";
  openTab(initialTab);
}

function openTab(tabId) {
  for (const item of document.querySelectorAll("[data-tab]")) {
    const active = item.dataset.tab === tabId;
    item.classList.toggle("active", active);
    item.setAttribute("aria-selected", active ? "true" : "false");
  }
  for (const panel of document.querySelectorAll(".tab-panel")) {
    panel.classList.toggle("active", panel.id === tabId);
  }
  const keySection = document.querySelector(".key-section");
  if (keySection) keySection.hidden = tabId === "wordpress";
}

function bindCopyButtons() {
  for (const button of document.querySelectorAll("[data-copy]")) {
    button.addEventListener("click", async () => {
      const target = document.querySelector(button.dataset.copy);
      await navigator.clipboard.writeText(target?.textContent || "");
      button.textContent = state.lang === "ja" ? "コピーしました" : "Copied";
      setTimeout(() => applyLanguage(state.lang), 1400);
    });
  }
  document.querySelector("[data-copy-result]")?.addEventListener("click", async (event) => {
    const snippet = document.querySelector("[data-snippet-output]")?.value || "";
    await navigator.clipboard.writeText(snippet);
    event.currentTarget.textContent = state.lang === "ja" ? "コピーしました" : "Copied";
    setTimeout(() => applyLanguage(state.lang), 1400);
  });
}

function bindKeyForm() {
  const form = document.querySelector("#site-key-form");
  if (!form) return;
  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    const status = document.querySelector("[data-key-status]");
    const resultBox = document.querySelector("[data-key-result]");
    const apiBase = (config.apiBase || "").replace(/\/$/, "");
    if (!apiBase || apiBase.includes("YOUR-WORKER")) {
      status.textContent = state.lang === "ja"
        ? "config.js の apiBase を公開Worker URLに変更してください。"
        : "Set apiBase in config.js to your public Worker URL.";
      status.className = "form-status error";
      return;
    }
    status.textContent = state.lang === "ja" ? "発行中..." : "Issuing...";
    status.className = "form-status";
    resultBox.hidden = true;
    try {
      const formData = new FormData(form);
      const response = await fetch(`${apiBase}/api/site-key`, {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({
          siteUrl: formData.get("siteUrl"),
          email: formData.get("email")
        })
      });
      const payload = await response.json();
      if (!response.ok || !payload.ok) throw new Error(payload.error || "request_failed");
      document.querySelector("[data-site-key-output]").value = payload.siteKey;
      document.querySelector("[data-snippet-output]").value = payload.tagSnippet || `<script src="${config.tagUrl}" async data-webmcp-site-key="${payload.siteKey}"></script>`;
      resultBox.hidden = false;
      const liveSnippet = payload.tagSnippet || `<script src="${config.tagUrl}" async data-webmcp-site-key="${payload.siteKey}"></script>`;
      for (const el of document.querySelectorAll("#gtm-snippet, #tag-snippet")) {
        el.textContent = liveSnippet;
      }
      status.textContent = state.lang === "ja" ? "発行しました。" : "Issued.";
      status.className = "form-status success";
    } catch (error) {
      status.textContent = state.lang === "ja"
        ? `発行できませんでした: ${error.message}`
        : `Could not issue a key: ${error.message}`;
      status.className = "form-status error";
    }
  });
}
